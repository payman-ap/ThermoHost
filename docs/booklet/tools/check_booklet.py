"""Check the GitHub booklet using Python's standard library.

Run normally to validate. --write-navigation refreshes contents, previous/next
links, and publication statistics after a chapter edit. No application source
or hardware state is changed.
"""

from pathlib import Path
import argparse
import math
import re
import struct
from check_calculations import calculations
from urllib.parse import unquote, urlsplit


BOOK = Path(__file__).resolve().parents[1]
ROOT = BOOK.parents[1]
NAV_MARKER = '<!-- NAVIGATION -->'
CONTENTS_START = '<!-- CONTENTS -->'
CONTENTS_END = '<!-- END CONTENTS -->'
SOURCES = {
    '03': ['firmware/usb/usb_descriptors.c'],
    '05': ['firmware/usb/tusb_config.h'],
    '06': ['firmware/thermometer_usb.c'],
    '07': ['firmware/thermometer_usb.c'],
    '08': ['ThermoHost/ThermoDevice/ThermoDevice.h'],
    '09': ['firmware/thermometer_usb.c',
           'ThermoHost/ThermoDevice/FreshResponse.h'],
}
MAIN_FILES = [
    '01-digital-foundations.md', '02-usb-architecture.md',
    '03-enumeration-and-descriptors.md', '04-operating-system-drivers.md',
    '05-tinyusb.md', '06-peripherals-and-acquisition.md',
    '07-protocols-and-framing.md', '08-host-libraries-and-ownership.md',
    '09-state-machines-and-io.md', '10-capacity-and-bottlenecks.md',
    '11-streaming-and-real-time.md', '12-thermohost-case-study.md',
]
APPENDICES = ['appendix-a-exercises.md', 'appendix-b-source-atlas.md',
              'appendix-c-references.md']


def title(path):
    return path.read_text(encoding='utf-8').splitlines()[0].removeprefix('# ')


def word_count(text):
    return len(re.findall(r'\b[\w-]+\b', text))


def slug(text):
    text = text.lower().replace('`', '')
    text = re.sub(r'[^\w\- ]', '', text)
    return text.replace(' ', '-')


def heading_ids(text):
    result = set()
    seen = {}
    for heading in re.findall(r'^#{1,6} (.+)$', text, re.M):
        base = slug(heading)
        count = seen.get(base, 0)
        seen[base] = count + 1
        result.add(base if not count else f'{base}-{count}')
    return result


def refresh(chapters):
    for index, path in enumerate(chapters):
        text = path.read_text(encoding='utf-8').split(NAV_MARKER)[0].rstrip()
        previous = chapters[index - 1] if index else None
        following = chapters[index + 1] if index + 1 < len(chapters) else None
        links = ['[Contents](README.md)']
        if previous:
            links.insert(0, f'[Previous: {title(previous)}]({previous.name})')
        if following:
            links.append(f'[Next: {title(following)}]({following.name})')
        path.write_text(text + '\n\n' + NAV_MARKER + '\n\n---\n\n'
                        + ' · '.join(links) + '\n', encoding='utf-8')

    index = BOOK / 'README.md'
    text = index.read_text(encoding='utf-8')
    entries = '\n'.join(f'{n}. [{re.sub(r"^\d+\. ", "", title(path))}]({path.name})'
                        for n, path in enumerate(chapters[:12], 1))
    entries += '\n\n' + '\n'.join(f'- [{title(path)}]({path.name})'
                                   for path in chapters[12:])
    contents = f'{CONTENTS_START}\n\n{entries}\n\n{CONTENTS_END}'
    if CONTENTS_END in text:
        text = re.sub(re.escape(CONTENTS_START) + r'.*?' + re.escape(CONTENTS_END),
                      lambda _: contents, text, flags=re.S)
    else:
        text = text.replace(CONTENTS_START, contents)
    index.write_text(text, encoding='utf-8')

    chapter_texts = [p.read_text(encoding='utf-8').split(NAV_MARKER)[0]
                     for p in chapters]
    manuscript_words = sum(word_count(t) for t in chapter_texts)
    # A disclosed planning estimate, not rendered/paginated PDF evidence.
    low_pages = math.ceil(manuscript_words / 300)
    high_pages = math.ceil(manuscript_words / 220)
    notes = f'''# Publication notes

This concept-first edition has twelve core chapters and three reference
appendices. It replaces the earlier 27-chapter structure rather than extending
it. ThermoHost is the running example after concepts are introduced.

- Core chapters and appendices: **{manuscript_words:,} words**, including code,
  tables, and link-label/URL text as counted by the checker, excluding navigation.
- Planning equivalent: approximately **{low_pages}–{high_pages} pages** at 220–300
  counted words per page. Figures, tables, code wrapping, margins, and chapter
  breaks can change actual pagination substantially. This is an estimate,
  not a claim of a rendered page count.
- Pure reading time at 180–220 counted words/minute: roughly
  **{manuscript_words / 220 / 60:.1f}–{manuscript_words / 180 / 60:.1f} hours**.
  Source study and practical exercises need additional sessions.
- Nine original PNG figures are generated by `assets/generate-assets.ps1`.
  Timelines and queue plots are explicitly illustrative, not board measurements.
- No firmware, Windows application code, or connected-device state was changed
  to create this booklet. Suggested code changes are exercises only.

## Checks and maintenance

From the repository root:

```powershell
python docs/booklet/tools/check_booklet.py
```

After changing chapter titles/order/content, refresh navigation and counts:

```powershell
python docs/booklet/tools/check_booklet.py --write-navigation
```

The checker verifies local destinations, the booklet's linked heading anchors,
previous/next navigation, fenced-code balance, PNG headers/dimensions, source
excerpt lines in order, selected protocol constants, worked byte examples,
and selected capacity/buffering/clock-drift calculations. The latter can also
be printed with `python docs/booklet/tools/check_calculations.py`.
It does not validate every technical sentence, fetch external links, compile
the quoted fragments, or perform hardware acceptance tests. Source excerpts are
checked ignoring whitespace and allowing omitted source lines between excerpt
lines; they remain teaching excerpts, not standalone programs.

The authoring pass inspected the figures, including the new TinyUSB layer
diagram. External sources are collected in [Appendix C](appendix-c-references.md).
The edition follows source inspected on 8 November 2026, after relocation of
the Windows solution to the root-level `ThermoHost/` directory.

[Return to contents](README.md)
'''
    (BOOK / 'publication-notes.md').write_text(notes, encoding='utf-8')


def check(chapters):
    errors = []
    snippets = 0
    links = 0
    for path in BOOK.glob('*.md'):
        text = path.read_text(encoding='utf-8')
        if text.count('```') % 2:
            errors.append(f'{path.name}: unbalanced code fences')
        for destination in re.findall(r'!?\[[^\]]*\]\(([^)]+)\)', text):
            parsed = urlsplit(destination)
            if parsed.scheme:
                continue
            links += 1
            target = (path.parent / unquote(parsed.path)).resolve() if parsed.path else path
            if not target.exists():
                errors.append(f'{path.name}: missing {destination}')
            elif parsed.fragment and target.suffix == '.md' and BOOK in target.parents:
                if unquote(parsed.fragment) not in heading_ids(target.read_text(encoding='utf-8')):
                    errors.append(f'{path.name}: unknown heading {destination}')
        for language, block in re.findall(r'```(c|cpp|cmake)\n(.*?)```', text, re.S):
            source_names = SOURCES.get(path.name[:2])
            if not source_names:
                errors.append(f'{path.name}: no excerpt source configured')
                continue
            matched = False
            for source_name in source_names:
                source = (ROOT / source_name).read_text(encoding='utf-8-sig')
                source_lines = [re.sub(r'\s+', '', line) for line in source.splitlines()]
                cursor = 0
                try:
                    for line in block.splitlines():
                        normalized = re.sub(r'\s+', '', line)
                        if normalized:
                            cursor = source_lines.index(normalized, cursor) + 1
                    matched = True
                    break
                except ValueError:
                    continue
            if not matched:
                errors.append(f'{path.name}: excerpt does not match its source files')
            snippets += 1

    for index, path in enumerate(chapters):
        text = path.read_text(encoding='utf-8')
        if NAV_MARKER not in text:
            errors.append(f'{path.name}: missing navigation')
            continue
        nav = text.split(NAV_MARKER)[1]
        expected = ['README.md']
        if index:
            expected.append(chapters[index - 1].name)
        if index + 1 < len(chapters):
            expected.append(chapters[index + 1].name)
        for name in expected:
            if f']({name})' not in nav:
                errors.append(f'{path.name}: missing navigation to {name}')

    images = list((BOOK / 'assets').glob('*.png'))
    if len(images) != 9:
        errors.append('Expected nine PNG figures')
    for path in images:
        data = path.read_bytes()
        if data[:8] != b'\x89PNG\r\n\x1a\n':
            errors.append(f'{path.name}: invalid PNG header')
        width, height = struct.unpack('>II', data[16:24])
        if min(width, height) < 800:
            errors.append(f'{path.name}: insufficient figure dimensions')

    wire = (ROOT / 'protocol/thermo_wire.h').read_text(encoding='utf-8')
    for name, value in [('THERMO_REQUEST_SIZE', 20), ('THERMO_RESPONSE_SIZE', 32),
                        ('THERMO_TOKEN_SIZE', 16)]:
        if not re.search(rf'#define\s+{name}\s+{value}\b', wire):
            errors.append(f'Source contract changed: {name}')
    # Execute the arithmetic presented in the text, independent of C++ builds.
    token = bytes(range(16))
    request = b'THQ2' + token
    response = b'THR2' + bytes(4) + struct.pack('<iI', 2550, 1000) + token
    expected = bytes.fromhex('54 48 52 32 00 00 00 00 F6 09 00 00 E8 03 00 00') + token
    assert len(request) == 20 and len(response) == 32 and response == expected
    assert struct.pack('<i', -1025).hex(' ').upper() == 'FF FB FF FF'
    assert struct.unpack('<i', bytes.fromhex('C4 09 00 00'))[0] / 100 == 25.0
    assert ((0x0330 >> 3) & 0xFFF) * 25 == 2550
    assert ((0x0550 >> 3) & 0xFFF) * 25 == 4250
    assert 0x0554 & 4 and 10 + 20 + 132 == 162
    calculations()
    if errors:
        raise SystemExit('\n'.join(errors))
    print(f'Passed: 12 chapters and 3 appendices, {links} local links, '
          f'{snippets} source excerpts, {len(images)} PNG figures, '
          'navigation and worked protocol arithmetic.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-navigation', action='store_true')
    arguments = parser.parse_args()
    expected_names = set(MAIN_FILES + APPENDICES)
    actual_names = {p.name for p in BOOK.glob('*.md')} - {'README.md', 'publication-notes.md'}
    if actual_names != expected_names:
        raise SystemExit(f'Manuscript file mismatch: {actual_names ^ expected_names}')
    chapter_paths = [BOOK / name for name in MAIN_FILES + APPENDICES]
    if arguments.write_navigation:
        refresh(chapter_paths)
    check(chapter_paths)
